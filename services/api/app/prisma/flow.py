"""Fold record_status_events into PRISMA 2020 flow counts and validate invariants.

Design rules (from the PRISMA validation doc):
  - Counts are folded from the append-only event log; never typed in by a person or generated by a model.
  - Only CURRENT events count; "current" = not superseded (id not referenced by any supersedes_id).
  - A flow is "final" only when every invariant holds AND pending counts are all zero.
  - The renderer must show which invariant fails; it must not silently suppress a violation.
  - Pathway A = databases/registers; Pathway B = other methods (citation search, websites, …).

Stdlib only.
"""

from __future__ import annotations

from dataclasses import dataclass, field
from typing import Any


@dataclass
class PrismaFlow:
    """All counts needed for a PRISMA 2020 flow diagram. Every field is a non-negative integer.
    `violations` is empty when all invariants pass. `is_final` is True when all pending = 0 and no violations."""

    # Pathway A
    identified_a: int = 0  # records identified from databases/registers (sum across sources)
    identified_a_by_source: dict[str, int] = field(default_factory=dict)  # {source_tag: count}
    removed_duplicates: int = 0
    removed_automation: int = 0
    removed_other: int = 0
    screened: int = 0  # = pending_ta + ta_excluded + ta_included
    pending_ta: int = 0
    ta_excluded: int = 0
    ta_included_a: int = 0  # sent to retrieval from pathway A

    # Pathway B
    identified_b: int = 0
    identified_b_by_source: dict[str, int] = field(default_factory=dict)
    ta_included_b: int = 0  # pathway B items that also went through TA screening (optional)

    # Retrieval (combined A+B)
    sought_retrieval: int = 0  # = pending_retrieval + not_retrieved + ft_assessed
    pending_retrieval: int = 0
    not_retrieved: int = 0
    ft_assessed: int = 0  # = pending_ft + ft_excluded + included_reports

    # Full-text
    pending_ft: int = 0
    ft_excluded: int = 0
    ft_excluded_by_reason: dict[str, int] = field(default_factory=dict)  # {reason_code: count}

    # Inclusion
    included_reports: int = 0
    included_studies: int = 0  # distinct study_id values; = included_reports when none grouped

    # Meta
    violations: list[dict[str, Any]] = field(default_factory=list)
    is_final: bool = False
    protocol_version_id: str | None = None


def validate(f: PrismaFlow) -> list[dict[str, Any]]:
    """Check PRISMA 2020 invariants V1–V11 (PRISMA validation doc). Returns a list of violations."""
    v: list[dict[str, Any]] = []

    def fail(vid: str, msg: str, **ctx: Any) -> None:
        v.append({"id": vid, "message": msg, **ctx})

    removed = f.removed_duplicates + f.removed_automation + f.removed_other

    # V1: identified_a = sum across sources
    src_sum = sum(f.identified_a_by_source.values())
    # V1: fire only when source counts exceed identified_a (over-counting).
    # Under-counting (src_sum < identified_a) is normal when some papers lack source_tag.
    if src_sum > f.identified_a:
        fail(
            "V1",
            "Sum of per-source records identified exceeds total records identified from databases.",
            identified_a=f.identified_a,
            source_sum=src_sum,
        )

    # V2: screened + removed + pending_before_screen = identified_a
    # (pending_before_screen is folded into identified_a - removed - screened; must be ≥ 0)
    before_screen_pending = f.identified_a - removed - f.screened
    if before_screen_pending < 0:
        fail(
            "V2",
            "Records removed plus screened exceeds records identified from databases.",
            identified_a=f.identified_a,
            removed=removed,
            screened=f.screened,
        )

    # V3: screened = pending_ta + ta_excluded + ta_included_a  (within pathway A)
    if f.screened != f.pending_ta + f.ta_excluded + f.ta_included_a:
        fail(
            "V3",
            "Screened count does not equal pending + excluded + sent to retrieval (pathway A).",
            screened=f.screened,
            pending_ta=f.pending_ta,
            ta_excluded=f.ta_excluded,
            ta_included_a=f.ta_included_a,
        )

    # V4: sought = ta_included_a + ta_included_b
    expected_sought = f.ta_included_a + f.ta_included_b
    if f.sought_retrieval != expected_sought:
        fail(
            "V4",
            "Reports sought for retrieval does not equal pathway A + pathway B inclusions.",
            sought_retrieval=f.sought_retrieval,
            expected=expected_sought,
        )

    # V5: sought = not_retrieved + ft_assessed + pending_retrieval
    if f.sought_retrieval != f.not_retrieved + f.ft_assessed + f.pending_retrieval:
        fail(
            "V5",
            "Reports sought does not equal not retrieved + assessed + pending retrieval.",
            sought_retrieval=f.sought_retrieval,
            not_retrieved=f.not_retrieved,
            ft_assessed=f.ft_assessed,
            pending_retrieval=f.pending_retrieval,
        )

    # V6: ft_assessed = ft_excluded + included_reports + pending_ft
    if f.ft_assessed != f.ft_excluded + f.included_reports + f.pending_ft:
        fail(
            "V6",
            "Reports assessed for eligibility does not equal excluded + included + pending.",
            ft_assessed=f.ft_assessed,
            ft_excluded=f.ft_excluded,
            included_reports=f.included_reports,
            pending_ft=f.pending_ft,
        )

    # V7: ft_excluded = sum of per-reason counts, all ≥ 0
    if f.ft_excluded > 0:
        reason_sum = sum(f.ft_excluded_by_reason.values())
        if any(n < 0 for n in f.ft_excluded_by_reason.values()):
            fail("V7", "A per-reason full-text exclusion count is negative.")
        elif reason_sum != f.ft_excluded:
            fail(
                "V7",
                "Sum of per-reason full-text exclusions does not equal total full-text excluded.",
                ft_excluded=f.ft_excluded,
                reason_sum=reason_sum,
            )

    # V8: included studies ≤ included reports, and at least 1 study if reports ≥ 1
    if f.included_reports > 0:
        if not (1 <= f.included_studies <= f.included_reports):
            fail(
                "V8",
                "Included studies must be between 1 and included reports.",
                included_reports=f.included_reports,
                included_studies=f.included_studies,
            )

    # V9: no negative counts
    for fname, val in vars(f).items():
        if isinstance(val, int) and val < 0:
            fail("V9", f"Negative count: {fname} = {val}.", field=fname, value=val)

    # V11: pending counts must be 0 for a final diagram
    pending_total = f.pending_ta + f.pending_retrieval + f.pending_ft
    if pending_total == 0 and not v:
        pass  # genuinely final
    # (V11 is reflected in is_final, not a violation itself)

    return v


# Stages that can only be reached after a record passed title/abstract screening.
FULL_TEXT_OUTCOMES = ("not_retrieved", "ft_excluded", "included")


def compute(raw_events: list[dict[str, Any]]) -> PrismaFlow:
    """Fold record_status_event dicts into PRISMA 2020 counts.

    Each paper journey is reconstructed from all events ordered by created_at ASC.
    Identification comes from the FIRST event; transition counts (ta_included, etc.)
    from EVERY event; pending counts from the LAST (current) event.
    Each dict: paper_id, stage, pathway, source_tag?, reason_code?, study_id?.
    """
    paper_events: dict[str, list[dict[str, Any]]] = {}
    for ev in raw_events:
        pid = str(ev["paper_id"])
        paper_events.setdefault(pid, []).append(ev)

    f = PrismaFlow()

    for evs in paper_events.values():
        first = evs[0]

        # Identification from first event
        pathway: str = str(first.get("pathway") or "A")
        src: str | None = first.get("source_tag")
        if pathway == "A":
            f.identified_a += 1
            if src:
                f.identified_a_by_source[src] = f.identified_a_by_source.get(src, 0) + 1
        else:
            f.identified_b += 1
            if src:
                f.identified_b_by_source[src] = f.identified_b_by_source.get(src, 0) + 1

        # Transition counts from every event in this paper's journey
        for ev in evs:
            stage: str = str(ev["stage"])
            pwy: str = str(ev.get("pathway") or pathway)
            if stage == "removed_before_screen":
                rc = str(ev.get("reason_code") or "other")
                if rc == "duplicate":
                    f.removed_duplicates += 1
                elif rc == "automation_ineligible":
                    f.removed_automation += 1
                else:
                    f.removed_other += 1
            elif stage == "ta_excluded":
                f.ta_excluded += 1
            elif stage == "ta_included":
                if pwy == "A":
                    f.ta_included_a += 1
                else:
                    f.ta_included_b += 1
            elif stage == "not_retrieved":
                f.not_retrieved += 1
            elif stage == "ft_excluded":
                f.ft_excluded += 1
                rc = str(ev.get("reason_code") or "unspecified")
                f.ft_excluded_by_reason[rc] = f.ft_excluded_by_reason.get(rc, 0) + 1
            elif stage == "included":
                f.included_reports += 1

        # A full-text outcome implies the record passed title/abstract screening. Each correction or forward
        # step supersedes the paper's previous event, so the explicit 'ta_included' event is no longer current
        # once a full-text outcome exists; count it from the outcome instead, so the record stays in
        # 'sought for retrieval' and does not fall back into 'awaiting title/abstract screening'.
        last = evs[-1]
        if str(last["stage"]) in FULL_TEXT_OUTCOMES and not any(str(e["stage"]) == "ta_included" for e in evs):
            if str(last.get("pathway") or pathway) == "A":
                f.ta_included_a += 1
            else:
                f.ta_included_b += 1

    # Current stage for each paper (last event = where the paper is now)
    all_last = [evs[-1] for evs in paper_events.values()]

    # screened = papers that entered TA screening = identified_a minus removed before screening.
    # This is the total column in the PRISMA diagram labelled 'Records screened'.
    removed = f.removed_duplicates + f.removed_automation + f.removed_other
    f.screened = max(0, f.identified_a - removed)

    # pending_ta = screened but not yet decided (last event still 'identified', i.e. in the queue)
    f.pending_ta = max(0, f.screened - f.ta_excluded - f.ta_included_a)
    f.pending_retrieval = sum(1 for ev in all_last if ev["stage"] == "ta_included")
    f.pending_ft = 0  # no explicit ft_pending stage yet

    f.sought_retrieval = f.ta_included_a + f.ta_included_b
    f.ft_assessed = f.ft_excluded + f.included_reports

    # Distinct studies among included papers
    study_ids: set[str] = set()
    for evs in paper_events.values():
        if evs[-1]["stage"] == "included":
            paper_pid = str(evs[0]["paper_id"])
            sid = next((str(ev.get("study_id")) for ev in evs if ev.get("study_id")), paper_pid)
            study_ids.add(sid)
    f.included_studies = len(study_ids) if study_ids else f.included_reports

    f.violations = validate(f)
    f.is_final = f.pending_ta == 0 and f.pending_retrieval == 0 and f.pending_ft == 0 and not f.violations
    return f
