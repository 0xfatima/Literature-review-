"""Object storage interface (ADR D5). Services depend on `ObjectStore`, never on a concrete adapter.

Keys are generated by the application (`projects/<project uuid>/documents/<document uuid>.pdf`), never taken from
user input, and are validated again here so an adapter can never be asked to escape its root.
Stdlib only.
"""

from __future__ import annotations

import re
from collections.abc import Iterator
from dataclasses import dataclass
from datetime import datetime
from pathlib import Path
from typing import BinaryIO, Protocol

MAX_KEY_LENGTH = 300
_SEGMENT = re.compile(r"^[a-z0-9][a-z0-9_.-]*$")


class StorageError(Exception):
    """The store could not complete an operation (I/O failure, bad key, misconfiguration)."""


class ObjectNotFound(StorageError):
    pass


@dataclass(frozen=True)
class ObjectInfo:
    key: str
    size: int
    modified_at: datetime


def validate_key(key: str) -> str:
    """Return the key if it is a safe relative key, else raise StorageError. Lower-case segments of
    [a-z0-9_.-] separated by single slashes; no empty, dot-leading or `..` segments; bounded length."""
    if not isinstance(key, str) or not key or len(key) > MAX_KEY_LENGTH:
        raise StorageError("invalid storage key")
    segments = key.split("/")
    if any(not _SEGMENT.match(seg) or seg.endswith(".") or ".." in seg for seg in segments):
        raise StorageError("invalid storage key")
    return key


def validate_prefix(prefix: str) -> str:
    """A prefix is a key-like path ending in '/'. The empty prefix is refused so nothing can wipe a whole store."""
    if not prefix.endswith("/") or len(prefix) < 2:
        raise StorageError("invalid storage prefix")
    validate_key(prefix[:-1])
    return prefix


class ObjectStore(Protocol):
    name: str

    def put_file(self, key: str, src: Path) -> int:
        """Store the file at `src` under `key` atomically (readers never see a partial object). Returns its size."""

    def open(self, key: str) -> BinaryIO:
        """Open for binary reading. Raises ObjectNotFound."""

    def download_to(self, key: str, dest: Path) -> None:
        """Copy the object to `dest`. Raises ObjectNotFound."""

    def exists(self, key: str) -> bool: ...

    def delete(self, key: str) -> bool:
        """Delete one object. Idempotent: returns False if it was already gone."""

    def delete_prefix(self, prefix: str) -> int:
        """Delete every object under `prefix` (which must end in '/'). Returns how many were removed."""

    def list_objects(self, prefix: str) -> Iterator[ObjectInfo]: ...
