from __future__ import annotations

import uuid
from datetime import datetime
from typing import Any

from pydantic import BaseModel, ConfigDict, Field

from app.services.conversation_service import MAX_MESSAGE_CHARS, MAX_TITLE


class ConversationCreate(BaseModel):
    title: str | None = Field(default=None, min_length=1, max_length=MAX_TITLE)


class ConversationUpdate(BaseModel):
    expected_version: int = Field(ge=1)
    title: str = Field(min_length=1, max_length=MAX_TITLE)


class ConversationOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    project_id: uuid.UUID
    title: str
    title_source: str
    message_count: int
    row_version: int
    created_at: datetime
    updated_at: datetime
    last_message_at: datetime | None


class ConversationList(BaseModel):
    items: list[ConversationOut]
    total: int
    limit: int
    offset: int


class MessageCreate(BaseModel):
    content: str = Field(min_length=1, max_length=MAX_MESSAGE_CHARS)
    # Generated by the client per send attempt series; retries reuse it so a message is stored exactly once.
    client_message_id: uuid.UUID | None = None


class MessageOut(BaseModel):
    model_config = ConfigDict(from_attributes=True)
    id: uuid.UUID
    conversation_id: uuid.UUID
    seq: int
    role: str
    author_id: uuid.UUID | None
    content: str
    payload: dict[str, Any] | None
    client_message_id: uuid.UUID | None
    created_at: datetime


class MessagePage(BaseModel):
    conversation: ConversationOut
    items: list[MessageOut]
    has_older: bool


class MessagePosted(BaseModel):
    message: MessageOut
    conversation: ConversationOut
