"use client";
import { useQuery } from "@tanstack/react-query";
import { apiFetch } from "@/lib/api";
import type { PrismaFlow, PrismaViolation } from "@/lib/types";

function FlowRow({ label, value, indent = false }: { label: string; value: number; indent?: boolean }) {
  return (
    <div
      className={`flex items-baseline justify-between gap-4 py-1 text-sm ${indent ? "pl-6 text-muted" : ""}`}
    >
      <span>{label}</span>
      <span className="font-mono font-medium tabular-nums">{value.toLocaleString()}</span>
    </div>
  );
}

function ViolationBanner({ violations }: { violations: PrismaViolation[] }) {
  if (violations.length === 0) return null;
  return (
    <div className="rounded border border-danger bg-danger/10 p-3" role="alert">
      <p className="text-sm font-medium text-danger">
        {violations.length} count inconsistenc{violations.length === 1 ? "y" : "ies"} detected. The flow is
        not complete until these are resolved.
      </p>
      <ul className="mt-1 list-inside list-disc text-xs text-danger">
        {violations.map((v) => (
          <li key={v.id}>
            <strong>{v.id}:</strong> {v.message}
          </li>
        ))}
      </ul>
    </div>
  );
}

function PendingNote({ count, label }: { count: number; label: string }) {
  if (count === 0) return null;
  return (
    <p className="text-xs text-mark">
      {count.toLocaleString()} record{count === 1 ? "" : "s"} {label}
    </p>
  );
}

export default function PrismaFlowPanel({
  projectId,
  onOpenFullText,
}: {
  projectId: string;
  onOpenFullText?: () => void;
}) {
  const { data, isLoading, isError } = useQuery({
    queryKey: ["prisma", projectId, "flow"],
    queryFn: () => apiFetch<PrismaFlow>(`/projects/${projectId}/prisma/flow`),
    refetchInterval: 10_000, // flow changes as decisions are made
  });

  if (isLoading) return <p className="text-muted">Loading flow…</p>;
  if (isError || !data) return <p className="text-danger">Could not load the PRISMA flow.</p>;

  const f = data;
  const removed = f.removed_duplicates + f.removed_automation + f.removed_other;

  return (
    <div className="flex max-w-2xl flex-col gap-4">
      <div>
        <h2 className="section-title mb-1">PRISMA 2020 record flow</h2>
        <p className="text-xs text-muted">
          Counts are derived from the record-status event log. They update automatically as you make screening
          decisions. No counts are typed in manually or generated by AI.
        </p>
        {f.is_final && (
          <p className="mt-1 text-xs text-ok font-medium">
            All decisions are recorded — this flow is complete.
          </p>
        )}
      </div>

      <ViolationBanner violations={f.violations} />

      <section className="rounded border border-line bg-panel p-4" aria-labelledby="flow-a">
        <h3 id="flow-a" className="section-title mb-2">
          Identification — databases and registers (Pathway A)
        </h3>
        <FlowRow label="Records identified" value={f.identified_a} />
        {Object.entries(f.identified_a_by_source).map(([src, n]) => (
          <FlowRow key={src} label={src} value={n} indent />
        ))}
        {removed > 0 && (
          <div className="mt-2 border-t border-line pt-2">
            <p className="text-xs text-muted mb-1">Removed before screening</p>
            <FlowRow label="Duplicates removed" value={f.removed_duplicates} indent />
            <FlowRow label="Removed by automation tools" value={f.removed_automation} indent />
            <FlowRow label="Removed for other reasons" value={f.removed_other} indent />
          </div>
        )}
      </section>

      <section className="rounded border border-line bg-panel p-4" aria-labelledby="flow-screen">
        <h3 id="flow-screen" className="section-title mb-2">
          Title and abstract screening
        </h3>
        <FlowRow label="Records screened" value={f.screened} />
        <FlowRow label="Records excluded" value={f.ta_excluded} indent />
        <FlowRow label="Sent to retrieval" value={f.ta_included_a} indent />
        <PendingNote count={f.pending_ta} label="still awaiting a title/abstract decision" />
      </section>

      {f.identified_b > 0 && (
        <section className="rounded border border-line bg-panel p-4" aria-labelledby="flow-b">
          <h3 id="flow-b" className="section-title mb-2">
            Identification — other methods (Pathway B)
          </h3>
          <FlowRow label="Records identified" value={f.identified_b} />
          {Object.entries(f.identified_b_by_source).map(([src, n]) => (
            <FlowRow key={src} label={src} value={n} indent />
          ))}
        </section>
      )}

      <section className="rounded border border-line bg-panel p-4" aria-labelledby="flow-retrieval">
        <h3 id="flow-retrieval" className="section-title mb-2">
          Retrieval and full-text screening
        </h3>
        <FlowRow label="Reports sought for retrieval" value={f.sought_retrieval} />
        <FlowRow label="Reports not retrieved" value={f.not_retrieved} indent />
        <FlowRow label="Reports assessed for eligibility" value={f.ft_assessed} />
        <FlowRow label="Reports excluded (full text)" value={f.ft_excluded} indent />
        {Object.entries(f.ft_excluded_by_reason).map(([code, n]) => (
          <FlowRow key={code} label={code.replace(/_/g, " ")} value={n} indent />
        ))}
        <PendingNote count={f.pending_retrieval} label="still pending full-text retrieval" />
        <PendingNote count={f.pending_ft} label="still pending full-text assessment" />
        {onOpenFullText && f.sought_retrieval > 0 && (
          <button type="button" className="btn-secondary mt-2 self-start" onClick={onOpenFullText}>
            Open full-text screening
          </button>
        )}
      </section>

      <section className="rounded border border-line bg-panel p-4" aria-labelledby="flow-included">
        <h3 id="flow-included" className="section-title mb-2">
          Included
        </h3>
        <FlowRow label="Reports of included studies" value={f.included_reports} />
        <FlowRow label="Studies included" value={f.included_studies} />
        {f.included_reports > f.included_studies && (
          <p className="mt-1 text-xs text-muted">
            {f.included_reports - f.included_studies} report
            {f.included_reports - f.included_studies === 1 ? "" : "s"} have been grouped into studies (Full
            text tab, &ldquo;Studies and reports&rdquo;).
          </p>
        )}
        {f.included_reports > 0 && f.included_reports === f.included_studies && (
          <p className="mt-1 text-xs text-muted">
            One report per study (the default assumption). Group several reports of the same study under
            &ldquo;Studies and reports&rdquo; in the Full text step.
          </p>
        )}
      </section>

      <p className="text-xs text-muted">
        The counts above follow the{" "}
        <a
          href="https://www.prisma-statement.org/prisma-2020"
          target="_blank"
          rel="noopener noreferrer"
          className="underline"
        >
          PRISMA 2020 reporting guideline
        </a>
        . They are computed from this application&rsquo;s records; they are not a substitute for the official
        PRISMA checklist.
      </p>
    </div>
  );
}
